function rectangle = insetRectangle(rectangle, inset)
rectangle = [
    rectangle(1) + inset
    rectangle(2) + inset
    max(rectangle(3) - 2 * inset, 0)
    max(rectangle(4) - 2 * inset, 0)
    ].';
end

function intersects = segmentIntersectsRectangle( ...
        startPoint, endPoint, rectangle)
if rectangle(3) <= 0 || rectangle(4) <= 0
    intersects = false;
    return
end

minimumX = rectangle(1);
maximumX = rectangle(1) + rectangle(3);
minimumY = rectangle(2);
maximumY = rectangle(2) + rectangle(4);
delta = endPoint - startPoint;
p = [-delta(1), delta(1), -delta(2), delta(2)];
q = [
    startPoint(1) - minimumX
    maximumX - startPoint(1)
    startPoint(2) - minimumY
    maximumY - startPoint(2)
    ].';
lowerParameter = 0;
upperParameter = 1;

for index = 1:4
    if abs(p(index)) < eps
        if q(index) < 0
            intersects = false;
            return
        end
        continue
    end
    candidate = q(index) / p(index);
    if p(index) < 0
        lowerParameter = max(lowerParameter, candidate);
    else
        upperParameter = min(upperParameter, candidate);
    end
    if lowerParameter > upperParameter
        intersects = false;
        return
    end
end
intersects = true;
end

function [interacts, interactionKind, interactionPoint, measurement] = ...
        polylineInteraction(firstPath, secondPath, rules)
interacts = false;
interactionKind = "";
interactionPoint = [NaN, NaN];
measurement = NaN;
for firstSegment = 1:2
    for secondSegment = 1:2
        [segmentInteracts, segmentKind, segmentPoint, ...
            segmentMeasurement] = segmentInteraction( ...
            firstPath(firstSegment, :), ...
            firstPath(firstSegment + 1, :), ...
            secondPath(secondSegment, :), ...
            secondPath(secondSegment + 1, :), rules);
        if ~segmentInteracts
            continue
        end
        nearPathEndpoint = pointNearPathEndpoint( ...
            segmentPoint, firstPath, secondPath, ...
            rules.PathInteractionEndpointAllowancePixels);
        if nearPathEndpoint && ...
                segmentKind ~= "partial collinear overlap"
            continue
        end
        if nearPathEndpoint && ...
                segmentMeasurement <= ...
                2 * rules.PathInteractionEndpointAllowancePixels
            continue
        end
        interacts = true;
        interactionKind = segmentKind;
        interactionPoint = segmentPoint;
        measurement = segmentMeasurement;
        return
    end
end
end

function [interacts, interactionKind, interactionPoint, measurement] = ...
        segmentInteraction(firstStart, firstEnd, ...
        secondStart, secondEnd, rules)
interacts = false;
interactionKind = "";
interactionPoint = [NaN, NaN];
measurement = NaN;
firstVector = firstEnd - firstStart;
secondVector = secondEnd - secondStart;
firstLength = norm(firstVector);
secondLength = norm(secondVector);
if firstLength <= eps || secondLength <= eps
    return
end

vectorCross = cross2d(firstVector, secondVector);
relativeStart = secondStart - firstStart;
parallelMeasure = abs(vectorCross) / (firstLength * secondLength);
if parallelMeasure <= 1e-8
    lineDistance = abs(cross2d(relativeStart, firstVector)) / ...
        firstLength;
    if lineDistance > rules.GeometryTolerancePixels
        return
    end
    firstDirection = firstVector / firstLength;
    secondParameters = [
        dot(secondStart - firstStart, firstDirection)
        dot(secondEnd - firstStart, firstDirection)
        ];
    overlapStart = max(0, min(secondParameters));
    overlapEnd = min(firstLength, max(secondParameters));
    overlapLength = overlapEnd - overlapStart;
    if overlapLength < rules.MinimumPartialPathOverlapPixels
        return
    end
    interacts = true;
    interactionKind = "partial collinear overlap";
    interactionPoint = firstStart + ...
        0.5 * (overlapStart + overlapEnd) * firstDirection;
    measurement = overlapLength;
    return
end

firstParameter = cross2d(relativeStart, secondVector) / vectorCross;
secondParameter = cross2d(relativeStart, firstVector) / vectorCross;
parameterTolerance = 1e-9;
if firstParameter < -parameterTolerance || ...
        firstParameter > 1 + parameterTolerance || ...
        secondParameter < -parameterTolerance || ...
        secondParameter > 1 + parameterTolerance
    return
end
interacts = true;
interactionKind = "segment crossing";
interactionPoint = firstStart + firstParameter * firstVector;
measurement = 1;
end

function nearEndpoint = pointNearPathEndpoint( ...
        point, firstPath, secondPath, allowance)
pathEndpoints = [
    firstPath(1, :)
    firstPath(3, :)
    secondPath(1, :)
    secondPath(3, :)
    ];
nearEndpoint = any(vecnorm(pathEndpoints - point, 2, 2) <= allowance);
end

function result = cross2d(firstVector, secondVector)
result = firstVector(1) * secondVector(2) - ...
    firstVector(2) * secondVector(1);
end

function pathPoints = transitionPathPoints(transitionGeometry, index)
pathPoints = [
    transitionGeometry.SourceEndpoint(index, :)
    transitionGeometry.MidPoint(index, :)
    transitionGeometry.DestinationEndpoint(index, :)
    ];
end

function complete = routingGeometryIsComplete(transitionGeometry, index)
pathPoints = transitionPathPoints(transitionGeometry, index);
labelPosition = transitionGeometry.LabelPosition(index, :);
sourceOClock = transitionGeometry.SourceOClock(index);
destinationOClock = transitionGeometry.DestinationOClock(index);
complete = all(isfinite(pathPoints), "all") && ...
    all(isfinite(labelPosition)) && ...
    labelPosition(3) >= 0 && labelPosition(4) >= 0 && ...
    isfinite(sourceOClock) && sourceOClock >= 0 && ...
    sourceOClock <= 12 && ...
    isfinite(destinationOClock) && destinationOClock >= 0 && ...
    destinationOClock <= 12 && ...
    approximatePathLength(pathPoints) > eps;
end

function detail = routingCompletenessDetail( ...
        transitionGeometry, index, destinationPresent)
parts = strings(5, 1);
partCount = 0;
pathPoints = transitionPathPoints(transitionGeometry, index);
labelPosition = transitionGeometry.LabelPosition(index, :);
sourceOClock = transitionGeometry.SourceOClock(index);
destinationOClock = transitionGeometry.DestinationOClock(index);

if ~destinationPresent
    partCount = partCount + 1;
    parts(partCount) = "destination is missing";
end
if any(~isfinite(pathPoints), "all") || ...
        approximatePathLength(pathPoints) <= eps
    partCount = partCount + 1;
    parts(partCount) = "path endpoints or midpoint are invalid";
end
if any(~isfinite(labelPosition)) || ...
        labelPosition(3) < 0 || labelPosition(4) < 0
    partCount = partCount + 1;
    parts(partCount) = "LabelPosition is invalid";
end
if ~isfinite(sourceOClock) || sourceOClock < 0 || sourceOClock > 12
    partCount = partCount + 1;
    parts(partCount) = "SourceOClock is outside [0,12]";
end
if ~isfinite(destinationOClock) || ...
        destinationOClock < 0 || destinationOClock > 12
    partCount = partCount + 1;
    parts(partCount) = "DestinationOClock is outside [0,12]";
end
detail = join(parts(1:partCount), "; ");
end

function lengthPixels = approximatePathLength(pathPoints)
segmentVectors = diff(pathPoints, 1, 1);
lengthPixels = sum(vecnorm(segmentVectors, 2, 2));
end

function samples = resamplePolyline(pathPoints, sampleCount)
segmentLengths = vecnorm(diff(pathPoints, 1, 1), 2, 2);
totalLength = sum(segmentLengths);
samples = zeros(sampleCount, 2);
if totalLength <= eps
    samples(:, :) = pathPoints(1, :);
    return
end

targets = linspace(0, totalLength, sampleCount).';
firstSegmentEnd = segmentLengths(1);
for index = 1:sampleCount
    target = targets(index);
    if target <= firstSegmentEnd && segmentLengths(1) > eps
        fraction = target / segmentLengths(1);
        samples(index, :) = pathPoints(1, :) + ...
            fraction * (pathPoints(2, :) - pathPoints(1, :));
    elseif segmentLengths(2) > eps
        fraction = (target - firstSegmentEnd) / segmentLengths(2);
        fraction = min(max(fraction, 0), 1);
        samples(index, :) = pathPoints(2, :) + ...
            fraction * (pathPoints(3, :) - pathPoints(2, :));
    else
        samples(index, :) = pathPoints(2, :);
    end
end
end

function inside = pointInsideRectangle(point, rectangle, tolerance)
inside = point(1) > rectangle(1) + tolerance && ...
    point(1) < rectangle(1) + rectangle(3) - tolerance && ...
    point(2) > rectangle(2) + tolerance && ...
    point(2) < rectangle(2) + rectangle(4) - tolerance;
end

function separation = circularClockSeparation(firstClock, secondClock)
rawSeparation = mod(abs(firstClock - secondClock), 12);
separation = min(rawSeparation, 12 - rawSeparation);
end

function [side, coordinate, travelSpan, clearance, envelope] = ...
        outerLaneDescriptor( ...
        transitionGeometry, stateGeometry, transitionIndex, rules)
side = "";
coordinate = NaN;
travelSpan = [NaN, NaN];
clearance = NaN;
envelope = [NaN, NaN, NaN, NaN];
siblingMask = stateGeometry.ParentKey == ...
    transitionGeometry.ParentKey(transitionIndex);
if ~any(siblingMask)
    return
end

positions = stateGeometry.Position(siblingMask, :);
minimumX = min(positions(:, 1));
minimumY = min(positions(:, 2));
maximumX = max(positions(:, 1) + positions(:, 3));
maximumY = max(positions(:, 2) + positions(:, 4));
envelope = [minimumX, minimumY, maximumX, maximumY];
midPoint = transitionGeometry.MidPoint(transitionIndex, :);
outsideDistances = [
    minimumY - midPoint(2)
    midPoint(2) - maximumY
    minimumX - midPoint(1)
    midPoint(1) - maximumX
    ];
[maximumOutsideDistance, sideIndex] = max(outsideDistances);
if maximumOutsideDistance <= rules.OuterLaneDetectionMarginPixels
    return
end

sideNames = ["top", "bottom", "left", "right"];
side = sideNames(sideIndex);
clearance = maximumOutsideDistance;
pathPoints = transitionPathPoints(transitionGeometry, transitionIndex);
if side == "top" || side == "bottom"
    coordinate = midPoint(2);
    travelSpan = [min(pathPoints(:, 1)), max(pathPoints(:, 1))];
else
    coordinate = midPoint(1);
    travelSpan = [min(pathPoints(:, 2)), max(pathPoints(:, 2))];
end
end

function distance = rectangleDistance(firstRectangle, secondRectangle)
horizontalGap = max([ ...
    secondRectangle(1) - ...
    (firstRectangle(1) + firstRectangle(3)), ...
    firstRectangle(1) - ...
    (secondRectangle(1) + secondRectangle(3)), ...
    0]);
verticalGap = max([ ...
    secondRectangle(2) - ...
    (firstRectangle(2) + firstRectangle(4)), ...
    firstRectangle(2) - ...
    (secondRectangle(2) + secondRectangle(4)), ...
    0]);
distance = hypot(horizontalGap, verticalGap);
end

function distance = pointToSegmentDistance(point, startPoint, endPoint)
segment = endPoint - startPoint;
segmentLengthSquared = dot(segment, segment);
if segmentLengthSquared <= eps
    distance = norm(point - startPoint);
    return
end
projection = dot(point - startPoint, segment) / segmentLengthSquared;
projection = min(max(projection, 0), 1);
closestPoint = startPoint + projection * segment;
distance = norm(point - closestPoint);
end

function present = hasReciprocalTransition(transitionGeometry, index)
candidateMask = transitionGeometry.SourceKey == ...
    transitionGeometry.DestinationKey(index) & ...
    transitionGeometry.DestinationKey == ...
    transitionGeometry.SourceKey(index);
candidateMask(index) = false;
present = any(candidateMask);
end

