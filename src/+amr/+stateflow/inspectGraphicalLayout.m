    deviation = pointToSegmentDistance( ...
        pathPoints(2, :), pathPoints(1, :), pathPoints(3, :));
    lengthRatio = approximatePathLength(pathPoints) / directLength;
    if deviation > rules.ShortTransitionMaximumDeviationPixels || ...
            lengthRatio > rules.ShortTransitionMaximumLengthRatio
        collector = appendViolation(collector, ...
            "ShortTransitionStraightness", ...
            transitionGeometry.ParentDisplay(index), ...
            transitionGeometry.Display(index), "", deviation, ...
            rules.ShortTransitionMaximumDeviationPixels, ...
            sprintf([ ...
            'Adjacent-state gap %.1f; midpoint deviation %.1f; ' ...
            'path/direct length ratio %.3f; path %s.'], ...
            stateGap, deviation, lengthRatio, ...
            mat2str(pathPoints, 5)));
