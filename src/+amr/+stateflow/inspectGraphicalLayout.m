        if pathSpan < rules.MinimumSelfLoopSpanPixels
            collector = appendViolation(collector, ...
                "SmallSelfLoopApproximation", ...
                transitionGeometry.ParentDisplay(index), ...
                transitionGeometry.Display(index), "", pathSpan, ...
                rules.MinimumSelfLoopSpanPixels, ...
                sprintf("Self-loop path span is %.1f pixels: %s.", ...
                pathSpan, mat2str(pathPoints, 5)));
        end
        continue
    end

    [outerLaneSide, ~] = outerLaneDescriptor( ...
        transitionGeometry, stateGeometry, index, rules);
    directVector = pathPoints(3, :) - pathPoints(1, :);
    directLength = norm(directVector);
    firstVector = pathPoints(2, :) - pathPoints(1, :);
    secondVector = pathPoints(3, :) - pathPoints(2, :);
    segmentNormProduct = norm(firstVector) * norm(secondVector);
    if directLength <= rules.GeometryTolerancePixels || ...
            directLength > rules.ShortTransitionMaximumLengthPixels || ...
            strlength(outerLaneSide) > 0 || ...
            segmentNormProduct <= eps
        continue
    end
    detourRatio = approximatePathLength(pathPoints) / directLength;
    turnCosine = dot(firstVector, secondVector) / segmentNormProduct;
    if detourRatio > rules.MaximumShortPathDetourRatio || ...
            turnCosine < rules.BacktrackingCosineThreshold
        collector = appendViolation(collector, ...
            "SmallLoopOrSShapeApproximation", ...
            transitionGeometry.ParentDisplay(index), ...
            transitionGeometry.Display(index), "", detourRatio, ...
            rules.MaximumShortPathDetourRatio, ...
            sprintf([ ...
            'Two-segment approximation has detour ratio %.3f and ' ...
            'turn cosine %.3f for path %s.'], ...
            detourRatio, turnCosine, mat2str(pathPoints, 5)));
    end
end
violations = finishCollector(collector);
end

function violations = inspectLabelPathOverlaps( ...
        transitionGeometry, rules)
transitionCount = numel(transitionGeometry.Key);
collector = createCollector(transitionCount * max(transitionCount - 1, 0));
for labelIndex = 1:transitionCount
    if strlength(strtrim(transitionGeometry.Label(labelIndex))) == 0
        continue
    end
    labelRectangle = insetRectangle( ...
        transitionGeometry.LabelPosition(labelIndex, :), ...
        rules.LabelPathInsetPixels);
    if labelRectangle(3) <= 0 || labelRectangle(4) <= 0
        continue
    end
    for pathIndex = 1:transitionCount
        if labelIndex == pathIndex || ...
                transitionGeometry.ParentKey(labelIndex) ~= ...
                transitionGeometry.ParentKey(pathIndex)
            continue
        end
        pathPoints = transitionPathPoints( ...
            transitionGeometry, pathIndex);
        overlapsPath = segmentIntersectsRectangle( ...
            pathPoints(1, :), pathPoints(2, :), labelRectangle) || ...
            segmentIntersectsRectangle( ...
            pathPoints(2, :), pathPoints(3, :), labelRectangle);
        if overlapsPath
            collector = appendViolation(collector, ...
                "LabelPathOverlap", ...
                transitionGeometry.ParentDisplay(labelIndex), ...
                transitionGeometry.Display(labelIndex), ...
                transitionGeometry.Display(pathIndex), 1, 0, ...
                sprintf([ ...
                'Inset label rectangle %s intersects another ' ...
                'transition two-segment path %s.'], ...
                mat2str(labelRectangle, 5), ...
                mat2str(pathPoints, 5)));
        end
    end
end
violations = finishCollector(collector);
end

function violations = inspectPathPathInteractions( ...
        transitionGeometry, rules)
transitionCount = numel(transitionGeometry.Key);
collector = createCollector( ...
    transitionCount * max(transitionCount - 1, 0) / 2);
for firstIndex = 1:transitionCount
    firstPath = transitionPathPoints(transitionGeometry, firstIndex);
    for secondIndex = firstIndex + 1:transitionCount
        if transitionGeometry.ParentKey(firstIndex) ~= ...
                transitionGeometry.ParentKey(secondIndex)
            continue
        end
        secondPath = transitionPathPoints( ...
            transitionGeometry, secondIndex);
        [interacts, interactionKind, interactionPoint, measurement] = ...
            polylineInteraction(firstPath, secondPath, rules);
        if interacts
            collector = appendViolation(collector, ...
                "PathPathCrossingOrPartialOverlap", ...
                transitionGeometry.ParentDisplay(firstIndex), ...
                transitionGeometry.Display(firstIndex), ...
                transitionGeometry.Display(secondIndex), ...
                measurement, 0, ...
                sprintf( ...
                '%s near %s. First path %s; second path %s.', ...
                interactionKind, mat2str(interactionPoint, 5), ...
                mat2str(firstPath, 5), mat2str(secondPath, 5)));
        end
    end
end
violations = finishCollector(collector);
end

function [overlapWidth, overlapHeight] = rectangleOverlap(first, second)
