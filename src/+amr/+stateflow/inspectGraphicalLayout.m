function violations = inspectCompletePathOverlaps( ...
        transitionGeometry, rules)
transitionCount = numel(transitionGeometry.Key);
collector = createCollector( ...
    transitionCount * max(transitionCount - 1, 0) / 2);
for firstIndex = 1:transitionCount
    firstPath = transitionPathPoints(transitionGeometry, firstIndex);
    firstLength = approximatePathLength(firstPath);
    if firstLength <= rules.GeometryTolerancePixels
        continue
    end
    firstSamples = resamplePolyline( ...
        firstPath, rules.RoutingSampleCount);
    for secondIndex = firstIndex + 1:transitionCount
        if transitionGeometry.ParentKey(firstIndex) ~= ...
                transitionGeometry.ParentKey(secondIndex)
            continue
        end
        secondPath = transitionPathPoints( ...
            transitionGeometry, secondIndex);
        secondLength = approximatePathLength(secondPath);
        if secondLength <= rules.GeometryTolerancePixels
            continue
        end
        relativeLengthDifference = abs(firstLength - secondLength) / ...
            max(firstLength, secondLength);
        if relativeLengthDifference > ...
                rules.CompletePathLengthRatioTolerance
            continue
        end
        secondSamples = resamplePolyline( ...
            secondPath, rules.RoutingSampleCount);
        forwardDistance = max(vecnorm( ...
            firstSamples - secondSamples, 2, 2));
        reverseDistance = max(vecnorm( ...
            firstSamples - flipud(secondSamples), 2, 2));
        pathDistance = min(forwardDistance, reverseDistance);
        if pathDistance <= rules.CompletePathOverlapTolerancePixels
            collector = appendViolation(collector, ...
                "CompletePathOverlap", ...
                transitionGeometry.ParentDisplay(firstIndex), ...
                transitionGeometry.Display(firstIndex), ...
                transitionGeometry.Display(secondIndex), ...
                pathDistance, ...
                rules.CompletePathOverlapTolerancePixels, ...
                sprintf([ ...
                'Complete sampled paths are within %.1f pixels. ' ...
                'First path %s; second path %s.'], ...
                pathDistance, mat2str(firstPath, 5), ...
                mat2str(secondPath, 5)));
        end
    end
end
violations = finishCollector(collector);
end

