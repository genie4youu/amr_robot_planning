    transitionGeometry.SourceKey(index) & ...
    transitionGeometry.DestinationKey == ...
    transitionGeometry.DestinationKey(index);
candidateMask(index) = false;
present = any(candidateMask);
end

function key = objectKey(object)
if isempty(object)
    key = "<none>";
elseif isa(object, "Stateflow.Chart")
    key = "Stateflow.Chart:" + string(object.Path);
elseif isprop(object, "SSIdNumber")
    key = string(class(object)) + ":" + ...
        string(double(object.SSIdNumber));
else
    key = string(class(object)) + ":" + objectDisplay(object);
end
end

function displayName = objectDisplay(object)
if isempty(object)
    displayName = "<none>";
elseif isa(object, "Stateflow.Chart")
    displayName = string(object.Path);
elseif isprop(object, "Name") && strlength(string(object.Name)) > 0
    displayName = string(object.Name);
    if isprop(object, "SSIdNumber")
        displayName = displayName + " [SSID " + ...
            string(double(object.SSIdNumber)) + "]";
    end
elseif isprop(object, "SSIdNumber")
    displayName = string(class(object)) + " [SSID " + ...
        string(double(object.SSIdNumber)) + "]";
else
    displayName = string(class(object));
end
end

function displayName = transitionDisplay(transition)
sourceName = objectDisplay(transition.Source);
destinationName = objectDisplay(transition.Destination);
label = replace(string(transition.LabelString), newline, " ");
label = strtrim(label);
if strlength(label) > 80
    label = extractBefore(label, 78) + "...";
end
displayName = "T" + string(double(transition.SSIdNumber)) + ...
    " " + sourceName + " -> " + destinationName;
if strlength(label) > 0
    displayName = displayName + " " + label;
end
end

function collector = createCollector(capacity)
capacity = max(1, ceil(capacity));
collector = struct;
collector.Count = 0;
collector.Category = strings(capacity, 1);
collector.Scope = strings(capacity, 1);
collector.ObjectA = strings(capacity, 1);
collector.ObjectB = strings(capacity, 1);
collector.Measurement = nan(capacity, 1);
collector.Required = nan(capacity, 1);
collector.Detail = strings(capacity, 1);
end

function collector = appendViolation(collector, category, scope, ...
        objectA, objectB, measurement, required, detail)
nextIndex = collector.Count + 1;
if nextIndex > numel(collector.Category)
    error("AMR:Stateflow:CollectorCapacityExceeded", ...
        "The graphical-layout violation collector capacity was exceeded.");
end
collector.Count = nextIndex;
collector.Category(nextIndex) = string(category);
collector.Scope(nextIndex) = string(scope);
collector.ObjectA(nextIndex) = string(objectA);
collector.ObjectB(nextIndex) = string(objectB);
collector.Measurement(nextIndex) = double(measurement);
collector.Required(nextIndex) = double(required);
collector.Detail(nextIndex) = string(detail);
end

function violations = finishCollector(collector)
indices = (1:collector.Count).';
violations = table( ...
    collector.Category(indices), ...
    collector.Scope(indices), ...
    collector.ObjectA(indices), ...
    collector.ObjectB(indices), ...
    collector.Measurement(indices), ...
    collector.Required(indices), ...
    collector.Detail(indices), ...
    VariableNames=[ ...
    "Category", "Scope", "ObjectA", "ObjectB", ...
    "Measurement", "Required", "Detail"]);
end

function diagnostic = formatDiagnostic(violations, emptyMessage)
if isempty(violations)
    diagnostic = string(emptyMessage);
else
    diagnostic = string(evalc("disp(violations)"));
end
end
