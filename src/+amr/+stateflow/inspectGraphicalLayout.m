    sourceMatches = find( ...
        stateGeometry.Key == transitionGeometry.SourceKey(index));
    destinationMatches = find( ...
        stateGeometry.Key == transitionGeometry.DestinationKey(index));
    if ~isscalar(sourceMatches) || ~isscalar(destinationMatches) || ...
            sourceMatches == destinationMatches || ...
            hasReciprocalTransition(transitionGeometry, index) || ...
            hasParallelTransition(transitionGeometry, index)
        continue
    end
    sourceRectangle = stateGeometry.Position(sourceMatches, :);
    destinationRectangle = stateGeometry.Position(destinationMatches, :);
    stateGap = rectangleDistance( ...
        sourceRectangle, destinationRectangle);
    pathPoints = transitionPathPoints(transitionGeometry, index);
    directLength = norm(pathPoints(3, :) - pathPoints(1, :));
