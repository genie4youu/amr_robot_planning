interiorIndices = firstInteriorIndex:lastInteriorIndex;

for firstIndex = 1:transitionCount
    if transitionGeometry.SourceKey(firstIndex) == "<none>"
        continue
    end
    for secondIndex = firstIndex + 1:transitionCount
        isReversePair = ...
            transitionGeometry.ParentKey(firstIndex) == ...
            transitionGeometry.ParentKey(secondIndex) && ...
            transitionGeometry.SourceKey(firstIndex) == ...
            transitionGeometry.DestinationKey(secondIndex) && ...
            transitionGeometry.DestinationKey(firstIndex) == ...
