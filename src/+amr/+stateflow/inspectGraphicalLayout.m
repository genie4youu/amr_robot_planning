function report = inspectGraphicalLayout(modelInput, chartInput)
%INSPECTGRAPHICALLAYOUT Inspect the graphical quality of a Stateflow chart.
%   REPORT = amr.stateflow.inspectGraphicalLayout(MODEL, CHART) loads MODEL
%   when necessary and inspects CHART without changing or saving the model.
%   MODEL is a model name or model file path. CHART is a Stateflow.Chart
%   object, a chart name, or a full chart path.
%
%   Hard violations cover sibling-state overlap, Stateflow-reported bad
%   intersections, the NavigationRegion row contract, fonts, transition
%   label overlap, transition paths through unrelated states, and crowded
%   outgoing transition endpoints. Routing diagnostics additionally inspect
%   the complete routing inventory and approximate path geometry. State text
%   fit is an advisory estimate because Stateflow does not expose the
%   rendered state-label extent.

narginchk(1, 2);
if nargin < 2
    chartInput = "MissionSupervisor";
end

mustBeTextScalar(modelInput);
[modelName, closeWhenDone] = ensureModelLoaded(string(modelInput));
cleanup = onCleanup(@() closeOwnedModel(modelName, closeWhenDone));
chart = resolveChart(modelName, chartInput);

rules = graphicalRules();
states = chart.find("-isa", "Stateflow.State");
transitions = chart.find("-isa", "Stateflow.Transition");
stateGeometry = collectStateGeometry(states);
transitionGeometry = collectTransitionGeometry(transitions);

badIntersections = inspectBadIntersections( ...
    states, stateGeometry);
stateOverlaps = inspectStateOverlaps(stateGeometry, rules);
navigationRegion = inspectNavigationRegion(stateGeometry, rules);
fontViolations = inspectFonts( ...
    chart, states, transitions, stateGeometry, transitionGeometry, rules);
labelStateOverlaps = inspectLabelStateOverlaps( ...
    transitionGeometry, stateGeometry, rules);
labelLabelOverlaps = inspectLabelLabelOverlaps( ...
    transitionGeometry, rules);
transitionStateCrossings = inspectTransitionStateCrossings( ...
    transitions, transitionGeometry, stateGeometry, rules);
outgoingEndpointSpacing = inspectOutgoingEndpointSpacing( ...
    transitions, transitionGeometry, rules);
stateTextFitAdvisories = inspectStateTextFit( ...
    states, stateGeometry, rules);
routingInventory = buildRoutingInventory( ...
    transitionGeometry, stateGeometry, rules);
routingCompleteness = inspectRoutingCompleteness( ...
    transitions, transitionGeometry);
completePathOverlaps = inspectCompletePathOverlaps( ...
    transitionGeometry, rules);
midPointStateIntersections = inspectMidPointStateIntersections( ...
    transitionGeometry, stateGeometry, rules);
selfLoopOClockViolations = inspectSelfLoopOClockSeparation( ...
    transitions, transitionGeometry, rules);
outerLaneSpacingViolations = inspectOuterLaneSpacing( ...
    transitionGeometry, stateGeometry, rules);
outerLaneEnvelopeClearanceViolations = ...
    inspectOuterLaneEnvelopeClearance( ...
    transitionGeometry, stateGeometry, rules);
excessiveOuterLaneClearanceViolations = ...
    inspectExcessiveOuterLaneClearance( ...
    transitionGeometry, stateGeometry, rules);
scopeCanvasInventory = buildScopeCanvasInventory( ...
    transitionGeometry, stateGeometry);
scopeCanvasBalanceViolations = inspectScopeCanvasBalance( ...
    scopeCanvasInventory, rules);
bidirectionalOuterDetourViolations = ...
    inspectBidirectionalOuterDetours( ...
    transitionGeometry, stateGeometry, rules);
shortTransitionStraightnessViolations = ...
    inspectShortTransitionStraightness( ...
    transitions, transitionGeometry, stateGeometry, rules);
bidirectionalTransitionViolations = ...
    inspectBidirectionalTransitionSeparation( ...
    transitionGeometry, rules);
pathShapeViolations = inspectApproximatePathShapes( ...
    transitionGeometry, stateGeometry, rules);
labelPathOverlaps = inspectLabelPathOverlaps( ...
    transitionGeometry, rules);
pathPathInteractions = inspectPathPathInteractions( ...
    transitionGeometry, rules);

hardViolations = [
    badIntersections
    stateOverlaps
    navigationRegion
    fontViolations
    labelStateOverlaps
    labelLabelOverlaps
    transitionStateCrossings
    outgoingEndpointSpacing
    ];
routingViolations = [
    routingCompleteness
    completePathOverlaps
    midPointStateIntersections
    selfLoopOClockViolations
    outerLaneSpacingViolations
    outerLaneEnvelopeClearanceViolations
    excessiveOuterLaneClearanceViolations
    scopeCanvasBalanceViolations
    bidirectionalOuterDetourViolations
    shortTransitionStraightnessViolations
    bidirectionalTransitionViolations
    pathShapeViolations
    labelPathOverlaps
    pathPathInteractions
    ];
exactRoutingViolations = [
    routingCompleteness
    midPointStateIntersections
    selfLoopOClockViolations
    excessiveOuterLaneClearanceViolations
    scopeCanvasBalanceViolations
    bidirectionalOuterDetourViolations
    ];
approximateRoutingViolations = [
    completePathOverlaps
    outerLaneSpacingViolations
    outerLaneEnvelopeClearanceViolations
    shortTransitionStraightnessViolations
    bidirectionalTransitionViolations
    pathShapeViolations
    labelPathOverlaps
    pathPathInteractions
    ];

report = struct;
report.Model = modelName;
report.Chart = string(chart.Path);
report.StateCount = uint32(numel(states));
report.TransitionCount = uint32(numel(transitions));
report.Rules = rules;
report.BadIntersections = badIntersections;
report.StateOverlaps = stateOverlaps;
report.NavigationRegion = navigationRegion;
report.FontViolations = fontViolations;
report.LabelStateOverlaps = labelStateOverlaps;
report.LabelLabelOverlaps = labelLabelOverlaps;
report.TransitionStateCrossings = transitionStateCrossings;
report.OutgoingEndpointSpacing = outgoingEndpointSpacing;
report.StateTextFitAdvisories = stateTextFitAdvisories;
report.HardViolations = hardViolations;
report.HardViolationCount = uint32(height(hardViolations));
report.AdvisoryCount = uint32(height(stateTextFitAdvisories));
report.Passed = isempty(hardViolations);
report.PathApproximation = ...
    "SourceEndpoint-to-MidPoint-to-DestinationEndpoint line segments";
report.HardDiagnostic = formatDiagnostic(hardViolations, ...
    "No hard graphical layout violations.");
report.AdvisoryDiagnostic = formatDiagnostic(stateTextFitAdvisories, ...
    "No state text-fit advisories.");
report.RoutingInventory = routingInventory;
report.RoutingCompletenessViolations = routingCompleteness;
report.RoutingCompletenessViolationCount = ...
    uint32(height(routingCompleteness));
report.CompletePathOverlaps = completePathOverlaps;
report.CompletePathOverlapCount = uint32(height(completePathOverlaps));
report.MidPointStateIntersections = midPointStateIntersections;
report.MidPointStateIntersectionCount = ...
    uint32(height(midPointStateIntersections));
report.SelfLoopOClockViolations = selfLoopOClockViolations;
report.SelfLoopOClockViolationCount = ...
    uint32(height(selfLoopOClockViolations));
report.OuterLaneSpacingViolations = outerLaneSpacingViolations;
report.OuterLaneSpacingViolationCount = ...
    uint32(height(outerLaneSpacingViolations));
report.OuterLaneEnvelopeClearanceViolations = ...
    outerLaneEnvelopeClearanceViolations;
report.OuterLaneEnvelopeClearanceViolationCount = ...
    uint32(height(outerLaneEnvelopeClearanceViolations));
report.ExcessiveOuterLaneClearanceViolations = ...
    excessiveOuterLaneClearanceViolations;
report.ExcessiveOuterLaneClearanceViolationCount = ...
    uint32(height(excessiveOuterLaneClearanceViolations));
report.ScopeCanvasInventory = scopeCanvasInventory;
report.ScopeCanvasBalanceViolations = scopeCanvasBalanceViolations;
report.ScopeCanvasBalanceViolationCount = ...
    uint32(height(scopeCanvasBalanceViolations));
report.BidirectionalOuterDetourViolations = ...
    bidirectionalOuterDetourViolations;
report.BidirectionalOuterDetourViolationCount = ...
    uint32(height(bidirectionalOuterDetourViolations));
report.ShortTransitionStraightnessViolations = ...
    shortTransitionStraightnessViolations;
report.ShortTransitionStraightnessViolationCount = ...
    uint32(height(shortTransitionStraightnessViolations));
report.BidirectionalTransitionViolations = ...
    bidirectionalTransitionViolations;
report.BidirectionalTransitionViolationCount = ...
    uint32(height(bidirectionalTransitionViolations));
report.PathShapeViolations = pathShapeViolations;
report.PathShapeViolationCount = uint32(height(pathShapeViolations));
report.LabelPathOverlaps = labelPathOverlaps;
report.LabelPathOverlapCount = uint32(height(labelPathOverlaps));
report.PathPathCrossingOrPartialOverlaps = pathPathInteractions;
report.PathPathCrossingOrPartialOverlapCount = ...
    uint32(height(pathPathInteractions));
report.RoutingViolations = routingViolations;
report.RoutingViolationCount = uint32(height(routingViolations));
report.RoutingPassed = isempty(routingViolations);
report.ExactRoutingViolations = exactRoutingViolations;
report.ExactRoutingViolationCount = ...
    uint32(height(exactRoutingViolations));
report.ExactRoutingPassed = isempty(exactRoutingViolations);
report.ApproximateRoutingViolations = approximateRoutingViolations;
report.ApproximateRoutingViolationCount = ...
    uint32(height(approximateRoutingViolations));
report.RoutingDiagnostic = formatDiagnostic(routingViolations, ...
    "No approximate transition-routing violations.");
report.RoutingLimitations = [
    "Stateflow exposes endpoints, one midpoint, and O'Clock values, " + ...
    "but not the rendered spline or all editor control points."
    "Path overlap, lane separation, straightness, and S-shape checks " + ...
    "therefore use two line segments and are conservative approximations."
    "Label-path and path-path checks use inset and endpoint allowances, " + ...
    "but rendered Stateflow splines can still create false positives."
    "The API does not reveal whether a valid MidPoint or O'Clock value " + ...
    "was assigned explicitly by a layout specification."
    ];

% Keep the cleanup object alive until the report is complete.
if isempty(cleanup)
    error("AMR:Stateflow:UnexpectedCleanupState", ...
        "The model cleanup guard was not created.");
end
end

