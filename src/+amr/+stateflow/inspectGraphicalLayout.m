firstBottom = first(2) + first(4);
secondRight = second(1) + second(3);
secondBottom = second(2) + second(4);
overlapWidth = min(firstRight, secondRight) - ...
    max(first(1), second(1));
overlapHeight = min(firstBottom, secondBottom) - ...
    max(first(2), second(2));
end

