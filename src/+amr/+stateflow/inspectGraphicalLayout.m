function [modelName, closeWhenDone] = ensureModelLoaded(modelInput)
[~, baseName, extension] = fileparts(modelInput);
if strlength(baseName) == 0
    baseName = modelInput;
end
modelName = string(baseName);
closeWhenDone = ~bdIsLoaded(modelName);

if closeWhenDone
    if strlength(extension) == 0 && ~contains(modelInput, filesep)
        load_system(char(modelName));
    else
        modelHandle = load_system(char(modelInput));
        modelName = string(get_param(modelHandle, "Name"));
    end
end
end

function closeOwnedModel(modelName, closeWhenDone)
if closeWhenDone && bdIsLoaded(modelName) && ...
        strcmp(get_param(modelName, "Dirty"), "off")
    close_system(modelName, 0);
end
end

function chart = resolveChart(modelName, chartInput)
root = sfroot;
if isa(chartInput, "Stateflow.Chart")
    chart = chartInput;
    if ~startsWith(string(chart.Path), modelName + "/")
        error("AMR:Stateflow:ChartModelMismatch", ...
            "Chart '%s' does not belong to model '%s'.", ...
            chart.Path, modelName);
    end
    return
end

mustBeTextScalar(chartInput);
selector = string(chartInput);
if startsWith(selector, modelName + "/")
    chartPath = selector;
else
    chartPath = modelName + "/" + selector;
end

matches = root.find( ...
    "-isa", "Stateflow.Chart", "Path", char(chartPath));
if isempty(matches)
    matches = findChartsByName(root, modelName, selector);
end
if numel(matches) ~= 1
    error("AMR:Stateflow:ChartNotUnique", ...
        "Expected one chart for selector '%s' in model '%s'; found %d.", ...
        selector, modelName, numel(matches));
end
chart = matches(1);
end

function matches = findChartsByName(root, modelName, selector)
allCharts = root.find("-isa", "Stateflow.Chart");
isMatch = false(size(allCharts));
for index = 1:numel(allCharts)
    chartPath = string(allCharts(index).Path);
    isMatch(index) = startsWith(chartPath, modelName + "/") && ...
        string(allCharts(index).Name) == selector;
end
matches = allCharts(isMatch);
end

function geometry = collectStateGeometry(states)
stateCount = numel(states);
geometry = struct;
geometry.Key = strings(stateCount, 1);
geometry.ParentKey = strings(stateCount, 1);
geometry.ParentDisplay = strings(stateCount, 1);
geometry.SubviewerKey = strings(stateCount, 1);
geometry.SubviewerDisplay = strings(stateCount, 1);
geometry.Name = strings(stateCount, 1);
geometry.Display = strings(stateCount, 1);
geometry.Position = zeros(stateCount, 4);
geometry.SSId = zeros(stateCount, 1);

for index = 1:stateCount
    parent = states(index).getParent;
    geometry.Key(index) = objectKey(states(index));
    geometry.ParentKey(index) = objectKey(parent);
    geometry.ParentDisplay(index) = objectDisplay(parent);
    geometry.SubviewerKey(index) = objectKey(states(index).Subviewer);
    geometry.SubviewerDisplay(index) = ...
        objectDisplay(states(index).Subviewer);
    geometry.Name(index) = string(states(index).Name);
    geometry.SSId(index) = double(states(index).SSIdNumber);
    geometry.Display(index) = geometry.Name(index) + ...
        " [SSID " + string(geometry.SSId(index)) + "]";
    geometry.Position(index, :) = double(states(index).Position);
end
end

