function violations = inspectBadIntersections(states, geometry)
collector = createCollector(numel(states));
for index = 1:numel(states)
    if logical(states(index).BadIntersection)
        collector = appendViolation(collector, ...
            "BadIntersection", geometry.ParentDisplay(index), ...
            geometry.Display(index), "", 1, 0, ...
            "Stateflow.State.BadIntersection is true.");
    end
end
violations = finishCollector(collector);
end

function violations = inspectStateOverlaps(geometry, rules)
stateCount = numel(geometry.Key);
collector = createCollector(stateCount * max(stateCount - 1, 0) / 2);
for firstIndex = 1:stateCount
    for secondIndex = firstIndex + 1:stateCount
        if geometry.ParentKey(firstIndex) ~= ...
                geometry.ParentKey(secondIndex)
            continue
        end
        [overlapWidth, overlapHeight] = rectangleOverlap( ...
            geometry.Position(firstIndex, :), ...
            geometry.Position(secondIndex, :));
        if overlapWidth > rules.GeometryTolerancePixels && ...
                overlapHeight > rules.GeometryTolerancePixels
            collector = appendViolation(collector, ...
                "StateOverlap", geometry.ParentDisplay(firstIndex), ...
                geometry.Display(firstIndex), ...
                geometry.Display(secondIndex), ...
                overlapWidth * overlapHeight, 0, ...
                sprintf([ ...
                'First rectangle %s; second rectangle %s; ' ...
                'overlap %.1f by %.1f pixels.'], ...
                mat2str(geometry.Position(firstIndex, :), 5), ...
                mat2str(geometry.Position(secondIndex, :), 5), ...
                overlapWidth, overlapHeight));
        end
    end
end
violations = finishCollector(collector);
end

function violations = inspectNavigationRegion(geometry, rules)
collector = createCollector(32);
regionMatches = find(geometry.Name == rules.NavigationRegionName);
if numel(regionMatches) ~= 1
    collector = appendViolation(collector, ...
        "NavigationRegion", "", rules.NavigationRegionName, "", ...
        numel(regionMatches), 1, ...
        "Expected exactly one NavigationRegion state.");
    violations = finishCollector(collector);
    return
end

regionIndex = regionMatches(1);
childMask = geometry.ParentKey == geometry.Key(regionIndex);
requiredNames = [
    rules.NavigationNormalRow
    rules.NavigationExceptionRow
    ];
childIndices = zeros(size(requiredNames));
for index = 1:numel(requiredNames)
    matches = find(childMask & geometry.Name == requiredNames(index));
    if isscalar(matches)
        childIndices(index) = matches;
    else
        collector = appendViolation(collector, ...
            "NavigationRegion", geometry.Display(regionIndex), ...
            requiredNames(index), "", numel(matches), 1, ...
            "Expected exactly one direct child with this name.");
    end
end

if all(childIndices > 0)
    normalIndices = childIndices(1, :);
    exceptionIndices = childIndices(2, :);
    collector = inspectHorizontalRow(collector, geometry, ...
        normalIndices, "normal", rules);
    collector = inspectHorizontalRow(collector, geometry, ...
        exceptionIndices, "exception", rules);
    for column = 1:size(childIndices, 2)
        topIndex = normalIndices(column);
        bottomIndex = exceptionIndices(column);
        topPosition = geometry.Position(topIndex, :);
        bottomPosition = geometry.Position(bottomIndex, :);
        verticalGap = bottomPosition(2) - ...
            (topPosition(2) + topPosition(4));
        if verticalGap < rules.MinimumVerticalGapPixels
            collector = appendViolation(collector, ...
                "NavigationVerticalGap", ...
                geometry.Display(regionIndex), ...
                geometry.Display(topIndex), ...
                geometry.Display(bottomIndex), verticalGap, ...
                rules.MinimumVerticalGapPixels, ...
                sprintf("Column %d vertical gap is %.1f pixels.", ...
                column, verticalGap));
        end
    end
end
violations = finishCollector(collector);
end

function collector = inspectHorizontalRow( ...
        collector, geometry, rowIndices, rowName, rules)
for column = 1:numel(rowIndices) - 1
    leftIndex = rowIndices(column);
    rightIndex = rowIndices(column + 1);
    leftPosition = geometry.Position(leftIndex, :);
    rightPosition = geometry.Position(rightIndex, :);
    horizontalGap = rightPosition(1) - ...
        (leftPosition(1) + leftPosition(3));
    if horizontalGap < rules.MinimumHorizontalGapPixels
        collector = appendViolation(collector, ...
            "NavigationHorizontalGap", ...
            geometry.ParentDisplay(leftIndex), ...
            geometry.Display(leftIndex), geometry.Display(rightIndex), ...
            horizontalGap, rules.MinimumHorizontalGapPixels, ...
            sprintf("%s row gap is %.1f pixels.", ...
            rowName, horizontalGap));
    end
end
end

function violations = inspectFonts( ...
        chart, states, transitions, stateGeometry, ...
        transitionGeometry, rules)
collector = createCollector(2 + numel(states) + numel(transitions));
chartStateFontSize = double(chart.StateFont.Size);
chartTransitionFontSize = double(chart.TransitionFont.Size);
if chartStateFontSize ~= rules.StateFontSize
    collector = appendViolation(collector, ...
        "StateFont", string(chart.Path), "Chart StateFont", "", ...
        chartStateFontSize, rules.StateFontSize, ...
        "Chart.StateFont.Size does not match the graphical standard.");
end
if chartTransitionFontSize ~= rules.TransitionFontSize
    collector = appendViolation(collector, ...
        "TransitionFont", string(chart.Path), ...
        "Chart TransitionFont", "", chartTransitionFontSize, ...
        rules.TransitionFontSize, ...
        "Chart.TransitionFont.Size does not match the graphical standard.");
end

for index = 1:numel(states)
    fontSize = double(states(index).FontSize);
    if fontSize ~= rules.StateFontSize
        collector = appendViolation(collector, ...
            "StateFont", stateGeometry.ParentDisplay(index), ...
            stateGeometry.Display(index), "", fontSize, ...
            rules.StateFontSize, ...
            "State.FontSize does not match the graphical standard.");
    end
end
for index = 1:numel(transitions)
    fontSize = double(transitions(index).FontSize);
    if fontSize ~= rules.TransitionFontSize
        collector = appendViolation(collector, ...
            "TransitionFont", ...
            transitionGeometry.ParentDisplay(index), ...
            transitionGeometry.Display(index), "", fontSize, ...
            rules.TransitionFontSize, ...
            "Transition.FontSize does not match the graphical standard.");
    end
end
violations = finishCollector(collector);
end

function violations = inspectLabelStateOverlaps( ...
        transitionGeometry, stateGeometry, rules)
transitionCount = numel(transitionGeometry.Key);
stateCount = numel(stateGeometry.Key);
collector = createCollector(transitionCount * stateCount);
for transitionIndex = 1:transitionCount
    if strlength(strtrim(transitionGeometry.Label(transitionIndex))) == 0
        continue
    end
    labelPosition = transitionGeometry.LabelPosition(transitionIndex, :);
    for stateIndex = 1:stateCount
        if transitionGeometry.ParentKey(transitionIndex) ~= ...
                stateGeometry.ParentKey(stateIndex)
            continue
        end
        [overlapWidth, overlapHeight] = rectangleOverlap( ...
            labelPosition, stateGeometry.Position(stateIndex, :));
        if overlapWidth > rules.GeometryTolerancePixels && ...
                overlapHeight > rules.GeometryTolerancePixels
            relation = labelStateRelation( ...
                transitionGeometry, transitionIndex, ...
                stateGeometry.Key(stateIndex));
            collector = appendViolation(collector, ...
                "LabelStateOverlap", ...
                transitionGeometry.ParentDisplay(transitionIndex), ...
                transitionGeometry.Display(transitionIndex), ...
                stateGeometry.Display(stateIndex), ...
                overlapWidth * overlapHeight, 0, ...
                sprintf([ ...
                'Relation=%s; label rectangle %s; state rectangle %s; ' ...
                'overlap %.1f by %.1f pixels.'], ...
                relation, mat2str(labelPosition, 5), ...
                mat2str(stateGeometry.Position(stateIndex, :), 5), ...
                overlapWidth, overlapHeight));
        end
    end
end
violations = finishCollector(collector);
end

function violations = inspectLabelLabelOverlaps(transitionGeometry, rules)
transitionCount = numel(transitionGeometry.Key);
collector = createCollector( ...
    transitionCount * max(transitionCount - 1, 0) / 2);
for firstIndex = 1:transitionCount
    if strlength(strtrim(transitionGeometry.Label(firstIndex))) == 0
        continue
    end
    for secondIndex = firstIndex + 1:transitionCount
        if transitionGeometry.ParentKey(firstIndex) ~= ...
                transitionGeometry.ParentKey(secondIndex) || ...
                strlength(strtrim( ...
                transitionGeometry.Label(secondIndex))) == 0
            continue
        end
        [overlapWidth, overlapHeight] = rectangleOverlap( ...
            transitionGeometry.LabelPosition(firstIndex, :), ...
            transitionGeometry.LabelPosition(secondIndex, :));
        if overlapWidth > rules.GeometryTolerancePixels && ...
                overlapHeight > rules.GeometryTolerancePixels
            collector = appendViolation(collector, ...
                "LabelLabelOverlap", ...
                transitionGeometry.ParentDisplay(firstIndex), ...
                transitionGeometry.Display(firstIndex), ...
                transitionGeometry.Display(secondIndex), ...
                overlapWidth * overlapHeight, 0, ...
                sprintf([ ...
                'First label rectangle %s; second label rectangle %s; ' ...
                'overlap %.1f by %.1f pixels.'], ...
                mat2str( ...
                transitionGeometry.LabelPosition(firstIndex, :), 5), ...
                mat2str( ...
                transitionGeometry.LabelPosition(secondIndex, :), 5), ...
                overlapWidth, overlapHeight));
        end
    end
end
violations = finishCollector(collector);
end

function violations = inspectTransitionStateCrossings( ...
        transitions, transitionGeometry, stateGeometry, rules)
transitionCount = numel(transitions);
stateCount = numel(stateGeometry.Key);
collector = createCollector(transitionCount * stateCount);
for transitionIndex = 1:transitionCount
    pathPoints = [
        transitionGeometry.SourceEndpoint(transitionIndex, :)
        transitionGeometry.MidPoint(transitionIndex, :)
        transitionGeometry.DestinationEndpoint(transitionIndex, :)
        ];
    if any(~isfinite(pathPoints), "all")
        collector = appendViolation(collector, ...
            "TransitionGeometry", ...
            transitionGeometry.ParentDisplay(transitionIndex), ...
            transitionGeometry.Display(transitionIndex), "", NaN, 0, ...
            "Transition endpoint or midpoint is not finite.");
        continue
    end
    sourceKey = objectKey(transitions(transitionIndex).Source);
    destinationKey = objectKey(transitions(transitionIndex).Destination);
    for stateIndex = 1:stateCount
        if transitionGeometry.ParentKey(transitionIndex) ~= ...
                stateGeometry.ParentKey(stateIndex) || ...
                stateGeometry.Key(stateIndex) == sourceKey || ...
                stateGeometry.Key(stateIndex) == destinationKey
            continue
        end
        testRectangle = insetRectangle( ...
            stateGeometry.Position(stateIndex, :), ...
            rules.GeometryTolerancePixels);
        crossesState = segmentIntersectsRectangle( ...
            pathPoints(1, :), pathPoints(2, :), testRectangle) || ...
            segmentIntersectsRectangle( ...
            pathPoints(2, :), pathPoints(3, :), testRectangle);
        if crossesState
            collector = appendViolation(collector, ...
                "TransitionStateCrossing", ...
                transitionGeometry.ParentDisplay(transitionIndex), ...
                transitionGeometry.Display(transitionIndex), ...
                stateGeometry.Display(stateIndex), 1, 0, ...
                sprintf([ ...
                'Path [source; midpoint; destination] %s crosses ' ...
                'unrelated state rectangle %s.'], ...
                mat2str(pathPoints, 5), ...
                mat2str(stateGeometry.Position(stateIndex, :), 5)));
        end
    end
end
violations = finishCollector(collector);
end

