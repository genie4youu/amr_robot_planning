% Rectangle rows use [x, y, width, height] in metres.

floorMap.bounds = [0.0, 12.0, 0.0, 8.0];
floorMap.walls = [ ...
    0.10, 0.10, 11.80, 0.16; ...
    0.10, 7.74, 11.80, 0.16; ...
    0.10, 0.10, 0.16, 7.80; ...
    11.74, 0.10, 0.16, 7.80; ...
    2.00, 2.00, 0.16, 3.40; ...
    4.00, 1.80, 3.20, 0.16; ...
    7.20, 1.80, 0.16, 1.15; ...
    7.20, 4.15, 0.16, 3.59; ...
    8.80, 4.15, 2.94, 0.16; ...
    4.00, 5.00, 0.16, 2.74];

floorMap.obstacles = [ ...
    0.45, 2.80, 0.35, 0.90; ...
    2.65, 5.65, 0.80, 1.30; ...
    8.10, 2.35, 1.10, 0.65; ...
    9.50, 0.75, 1.20, 0.65; ...
    9.25, 5.05, 0.70, 0.70];

