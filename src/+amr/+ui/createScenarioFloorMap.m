    floorMap.startPose(1:2), floorMap.goalPose(1:2));
floorMap.referenceRoute = amr.planning.smoothGridPath( ...
    planningGrid, rawReferenceRoute);

floorMap.labels = struct( ...
    "text", {"출발", "충전소", "창고 A", "창고 B", "배송 구역", "목표"}, ...
